# Template: everything before <section class="about"> and after </section>
# We'll extract it from the first article and reuse

def extract_template(filepath):
    """Extract head+header and footer+scripts from file."""
    content = filepath.read_text(encoding='utf-8')
    
    # Find section boundaries
    section_start = content.find('<section class="about">')
    section_end = content.find('</section>', section_start) + len('</section>')
    
    before = content[:section_start]
    after = content[section_end:]
    
    return before, after


def write_article(filename, before, after, new_section_html, year='2026'):
    """Write complete article file."""
    # Update year in before section
    before = before.replace('2025', year)
    
    full = before + new_section_html + after
    
    filepath = CONTENT_DIR / filename
    filepath.write_text(full, encoding='utf-8')
    
    # Count words in section
    text = re.sub(r'<[^>]+>', ' ', new_section_html)
    text = re.sub(r'\s+', ' ', text).strip()
    words = len(text.split())
    print(f'{filename}: {words} words written')
    return words


def get_template():
    """Get template from existing file."""
    before, after = extract_template(CONTENT_DIR / 'kakoj-stanok-vybrat-dlya-proizvodstva.html')
    return before, after


