function createSVGIcon(name, size) {
  const svg = document.createElement('div');
  svg.innerHTML = ICONS[name] || '';
  const el = svg.firstElementChild;
  if (el) {
    el.style.width = size + 'px';
    el.style.height = size + 'px';
    el.style.display = 'inline-block';
    el.style.verticalAlign = 'middle';
    el.style.flexShrink = '0';
  }
  return el;
}

// Replace emojis in service-icon, trust-icon, blog-card-image, icon, step-number containers
function replaceEmojiIcons() {
  // Elements where emoji is the only content
  document.querySelectorAll('.service-icon, .trust-icon, .blog-card-image').forEach(function(el) {
    var text = el.textContent.trim();
    var iconName = EMOJI_MAP[text];
    if (iconName && ICONS[iconName]) {
      el.textContent = '';
      el.appendChild(createSVGIcon(iconName, 24));
    }
  });
  // hero-badge: emoji at start, followed by text
  document.querySelectorAll('.hero-badge').forEach(function(el) {
    var text = el.textContent;
    for (var emoji in EMOJI_MAP) {
      if (text.indexOf(emoji) === 0) {
        var iconName = EMOJI_MAP[emoji];
        if (ICONS[iconName]) {
          el.textContent = '';
          el.appendChild(createSVGIcon(iconName, 16));
          el.appendChild(document.createTextNode(' ' + text.substring(emoji.length).trim()));
        }
        break;
      }
    }
  });
  // Icon spans (smaller)
  document.querySelectorAll('.icon').forEach(function(el) {
    var text = el.textContent.trim();
    var iconName = EMOJI_MAP[text];
    if (iconName && ICONS[iconName]) {
      el.textContent = '';
      el.appendChild(createSVGIcon(iconName, 18));
    }
  });
}

document.addEventListener('DOMContentLoaded', replaceEmojiIcons);
